import PocketBase from 'pocketbase';
import type { AuthUser, CategoryWithLinks, LinkDraft, LinkItem } from '../types/nav';

/* -------------------------------------------------------------------------- */
/* client                                                                      */
/* -------------------------------------------------------------------------- */

const rawUrl = (import.meta.env.VITE_PB_URL ?? '').trim();
export const PB_URL = rawUrl.replace(/\/+$/, '');

/**
 * Set when VITE_PB_URL is missing so the UI can explain the problem instead of
 * throwing at import time (which would leave a blank white page).
 */
export const PB_CONFIG_ERROR: string | null = PB_URL
  ? null
  : '未配置 VITE_PB_URL。请在 .env（本地）或托管平台的环境变量中填写 PocketBase 实例地址，然后重新构建。';

// The fallback host is never contacted: every caller bails out early when
// PB_CONFIG_ERROR is set.
export const pb = new PocketBase(PB_URL || 'http://127.0.0.1:8090');
// Disable auto-cancellation so rapid filter/typing reloads don't abort each other.
pb.autoCancellation(false);

// Collection names are namespaced so several projects can share one PocketBase
// instance. Keep in sync with `PB_PREFIX` in scripts/setup-pocketbase.mjs.
const CATEGORIES = 'aether_categories';
const LINKS = 'aether_links';
const EDITORS = 'aether_editors';

/* -------------------------------------------------------------------------- */
/* PocketBase record shapes (internal to this layer — components never see)   */
/* -------------------------------------------------------------------------- */

interface PbCategory {
  id: string;
  name: string;
  sort_order?: number;
  created: string;
}

interface PbLink {
  id: string;
  collectionId: string;
  collectionName: string;
  category: string;
  title: string;
  url: string;
  description?: string;
  icon?: string;
  sort_order?: number;
  created: string;
}

interface PbEditor {
  id: string;
  email: string;
}

/* -------------------------------------------------------------------------- */
/* mapping: PocketBase record -> component contract                           */
/* -------------------------------------------------------------------------- */

const THUMB = '64x64';

function toLinkItem(record: PbLink): LinkItem {
  return {
    id: record.id,
    category_id: record.category,
    title: record.title,
    url: record.url,
    description: record.description ?? '',
    // A file field stores only the filename; resolve it to a ready-to-use URL.
    // The 64x64 thumb keeps card payloads small and is generated by PocketBase.
    icon: record.icon ? pb.files.getURL(record, record.icon, { thumb: THUMB }) : '',
    sort_order: record.sort_order ?? 0,
    created_at: record.created,
  };
}

/* -------------------------------------------------------------------------- */
/* read                                                                       */
/* -------------------------------------------------------------------------- */

export async function loadNav(): Promise<CategoryWithLinks[]> {
  const [categories, links] = await Promise.all([
    pb.collection(CATEGORIES).getFullList<PbCategory>({ sort: 'sort_order,created' }),
    pb.collection(LINKS).getFullList<PbLink>({ sort: 'sort_order,created' }),
  ]);

  const linksByCategory = new Map<string, LinkItem[]>();
  for (const record of links) {
    const item = toLinkItem(record);
    const bucket = linksByCategory.get(item.category_id);
    if (bucket) bucket.push(item);
    else linksByCategory.set(item.category_id, [item]);
  }

  return categories.map((category) => ({
    id: category.id,
    name: category.name,
    sort_order: category.sort_order ?? 0,
    created_at: category.created,
    links: linksByCategory.get(category.id) ?? [],
  }));
}

/* -------------------------------------------------------------------------- */
/* categories                                                                 */
/* -------------------------------------------------------------------------- */

async function nextSortOrder(): Promise<number> {
  const latest = await pb.collection(CATEGORIES).getList<PbCategory>(1, 1, {
    sort: '-sort_order',
    fields: 'sort_order',
  });
  const current = latest.items[0]?.sort_order ?? 0;
  return current + 1;
}

export async function createCategory(name: string): Promise<void> {
  await pb.collection(CATEGORIES).create({ name, sort_order: await nextSortOrder() });
}

export async function updateCategory(id: string, name: string): Promise<void> {
  await pb.collection(CATEGORIES).update(id, { name });
}

export async function deleteCategory(id: string): Promise<void> {
  // Links are removed by PocketBase itself (relation field `cascadeDelete: true`).
  await pb.collection(CATEGORIES).delete(id);
}

/* -------------------------------------------------------------------------- */
/* links                                                                      */
/* -------------------------------------------------------------------------- */

const ICON_FILENAME: Record<string, string> = {
  'image/png': 'icon.png',
  'image/jpeg': 'icon.jpg',
  'image/webp': 'icon.webp',
  'image/x-icon': 'icon.ico',
  'image/gif': 'icon.gif',
};

function iconFilename(blob: Blob): string {
  return ICON_FILENAME[blob.type] ?? 'icon.png';
}

function buildLinkBody(draft: LinkDraft, icon: Blob | null): FormData | Record<string, unknown> {
  const fields: Record<string, string> = {
    category: draft.category_id,
    title: draft.title,
    url: draft.url,
    description: draft.description,
  };

  // Only switch to multipart when there is actually a file to upload. A plain
  // JSON body for the no-icon case keeps updates cheap and lets PocketBase keep
  // the existing icon file untouched.
  if (!icon) return fields;

  const form = new FormData();
  for (const [key, value] of Object.entries(fields)) form.set(key, value);
  form.set('icon', icon, iconFilename(icon));
  return form;
}

export async function createLink(draft: LinkDraft, icon: Blob | null = null): Promise<void> {
  await pb.collection(LINKS).create(buildLinkBody(draft, icon));
}

export async function updateLink(
  id: string,
  draft: LinkDraft,
  icon: Blob | null = null,
): Promise<void> {
  await pb.collection(LINKS).update(id, buildLinkBody(draft, icon));
}

export async function deleteLink(id: string): Promise<void> {
  await pb.collection(LINKS).delete(id);
}

/* -------------------------------------------------------------------------- */
/* auth (editors collection)                                                  */
/* -------------------------------------------------------------------------- */

export function currentUser(): AuthUser | null {
  const model = pb.authStore.model as PbEditor | null;
  if (!model?.id) return null;
  return { id: model.id, email: model.email ?? '' };
}

export function isLoggedIn(): boolean {
  return pb.authStore.isValid && currentUser() !== null;
}

export async function login(email: string, password: string): Promise<AuthUser> {
  const result = await pb
    .collection(EDITORS)
    .authWithPassword<PbEditor>(email.trim(), password);
  return { id: result.record.id, email: result.record.email };
}

export function logout(): void {
  pb.authStore.clear();
}

/** Subscribe to auth-store changes (login, logout, token refresh). */
export function subscribeAuth(listener: () => void): () => void {
  return pb.authStore.onChange(listener);
}
